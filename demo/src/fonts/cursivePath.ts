// Function to generate path for a word
export const generateWordPath = (word: string): string => {
  const letters = word.split('');
  let currentX = 20;
  let paths: string[] = [];
  
  letters.forEach((letter) => {
    if (cursivePaths[letter]) {
      // Add the letter path, offset by currentX
      const path = cursivePaths[letter].replace(/(\d+),/g, (_match: string, num: string) => {
        return `${parseInt(num) + currentX},`;
      });
      paths.push(path);
      currentX += 60; // Move to next letter position
    }
  });
  
  return paths.join(' ');
}; 